"""Makes src/pingpong/family.h: the 10 family members as 16x16 Game Boy Color faces, taken from the heads of the
GBA characters (gba/graphics/characters/chr_<name>.bmp, frame 0, the 16 rows from the top of the hair).

Every pixel becomes the closest of 3 colours: skin (1), hair (2) or outline (3). The second frame ("flap") is the
same face with the mouth open. Run after changing the GBA characters:
    python3 src/pingpong/make_family.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, os.path.join(ROOT, "gba", "tools", "art"))
from make_crowd import read_bmp  # noqa: E402
from make_characters import CHARACTERS, SKIN, HAIR  # noqa: E402

OUTLINE = (0x28, 0x20, 0x28)


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def dist(a, b):
    return sum((p - q) ** 2 for p, q in zip(a, b))


def gbc(c):
    return "RGB(%d,%d,%d)" % (c[0] >> 3, c[1] >> 3, c[2] >> 3)


def main():
    out = ["// Generated by src/pingpong/make_family.py from the GBA characters: don't edit by hand.",
           "// The family as 16x16 faces (1 skin, 2 hair, 3 outline) with a mouth-open second frame.",
           "#ifndef FAMILY_H", "#define FAMILY_H", "#include <gb/cgb.h>", "",
           "typedef struct {", "    const char *name;", "    const char * const *idle;", "    const char * const *flap;",
           "    palette_color_t pal[4];           // transparent, skin, hair, outline", "} character_t;", ""]
    entries = []
    for name, skin, hair, *_ in CHARACTERS:
        img = read_bmp(os.path.join(ROOT, "gba", "graphics", "characters", f"chr_{name.lower()}.bmp"))
        skin_c = hex_rgb(SKIN[skin][0])
        hair_c = hex_rgb(HAIR[hair][0])
        choices = [(skin_c, "1"), (hex_rgb(SKIN[skin][1]), "1"), (hair_c, "2"), (hex_rgb(HAIR[hair][1]), "2"),
                   (hex_rgb(HAIR[hair][2]), "2"), (OUTLINE, "3")]
        # Start at the top of the hair (the first row with anything drawn).
        top = next(y for y in range(32) if any(img.get(x, y) is not None for x in range(16)))
        rows = []
        for y in range(16):
            row = ""
            for x in range(16):
                p = img.get(x, top + y)
                if p is None:
                    row += "."
                else:
                    row += min(choices, key=lambda c: dist(p, c[0]))[1]
            rows.append(row)
        # Open mouth for the second frame: the lowest row of skin in the middle of the face gets a dark gap.
        flap = [list(r) for r in rows]
        for y in range(15, 6, -1):
            if flap[y][7] == "1" and flap[y][8] == "1":
                flap[y][7] = flap[y][8] = "3"
                break
        flap = ["".join(r) for r in flap]
        key = name.lower()
        for label, art in (("idle", rows), ("flap", flap)):
            out.append(f"static const char * const {key}_{label}[16] = {{")
            out += [f'    "{r}",' for r in art]
            out.append("};")
        entries.append(f'    {{ "{name.upper()}", {key}_idle, {key}_flap, {{ 0, {gbc(skin_c)}, {gbc(hair_c)}, {gbc(OUTLINE)} }} }},')
    out += ["", "static const character_t characters[] = {"] + entries + ["};",
            "#define NUM_CHARACTERS (sizeof(characters) / sizeof(characters[0]))", "", "#endif", ""]
    with open(os.path.join(HERE, "family.h"), "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote family.h with", len(entries), "characters")


if __name__ == "__main__":
    main()
